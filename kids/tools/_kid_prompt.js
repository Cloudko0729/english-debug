// 題幹的孩子端用語轉換。
//
// grammar_db 的 diagnostics.promptZh 是寫給教學引擎看的，有兩句樣板各出現 48 次
// （等於每一課都會出現）：
//   「哪一句最符合本節點的自然英文形式？」  ← 「本節點」是資料庫術語，小孩不知道那是什麼
//   「哪一句在一般情境中最自然，也不會改變核心意思？」← 太抽象、太書面
//
// 資料庫欄位不動（別處還在用，而且那是引擎語意），只在產生孩子看的頁面時換掉。
// 與 kid_wording.json 的處理原則一致：術語留在資料層，白話放在呈現層。
const KID_PROMPT = {
  "哪一句最符合本節點的自然英文形式？": "哪一句是對的？",
  "哪一句在一般情境中最自然，也不會改變核心意思？": "哪一句聽起來最自然？",
};

// 「哪一句最適合修正「X」？」這種本來就具體好懂，不在對照表裡就原樣保留。
function kidPrompt(zh) {
  return KID_PROMPT[String(zh || "").trim()] || zh || "哪一句是對的？";
}

module.exports = { kidPrompt, KID_PROMPT };
